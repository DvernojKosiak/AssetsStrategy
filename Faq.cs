    static int open = -1;
    static GUIStyle qSt, aSt;

    static void Styles()
    {
        if (qSt != null) return;
        qSt = new GUIStyle(UiKit.Body) { wordWrap = true, fontStyle = FontStyle.Bold, alignment = TextAnchor.MiddleLeft, richText = true };
        aSt = new GUIStyle(UiKit.Body) { wordWrap = true, richText = true };
    }

    static float QH(int i, float w) { return Mathf.Max(30f, UiKit.TextH(Items[i, 0], w - 30f, qSt) + 10f); }

    public static float Height(float w)
    {
        Styles();
        float h = 0f;
        for (int i = 0; i < Items.GetLength(0); i++)
        {
            h += QH(i, w) + 4f;
            if (open == i) h += UiKit.TextH(Items[i, 1], w - 16f, aSt) + 10f;
        }
        return h + 6f;
    }

    public static void Draw(Rect r)
    {
        Styles();
        float y = r.y, w = r.width;
        for (int i = 0; i < Items.GetLength(0); i++)
        {
            float qh = QH(i, w);
            Rect q = new Rect(r.x, y, w, qh);
            if (GUI.Button(q, GUIContent.none, UiKit.ButtonStyle(open == i ? UiKit.Kind.Primary : UiKit.Kind.Normal))) open = open == i ? -1 : i;
            LocGUI.Label(new Rect(q.x + 8f, q.y, 18f, qh), open == i ? "▾" : "▸", qSt);
            LocGUI.Label(new Rect(q.x + 26f, q.y, w - 32f, qh), Items[i, 0], qSt);
            y += qh + 4f;
            if (open == i)
            {
                float ah = UiKit.TextH(Items[i, 1], w - 16f, aSt);
                LocGUI.Label(new Rect(r.x + 8f, y, w - 16f, ah), Items[i, 1], aSt);
                y += ah + 10f;
            }
        }
    }
